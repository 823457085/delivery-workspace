import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { executeProjectGitAction, readProjectGitSnapshot, readProjectDiff, readProjectCode, readProjectTree } from '../server/project-git';
import type { SourceBackend } from '../server/source-backend';
const exec = promisify(execFile);

test('真实本地仓库：差异、暂存、提交、分支、合并、远端同步及冲突恢复', async () => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'delivery-git-'));
  const repo = path.join(directory, 'repo'), remote = path.join(directory, 'remote.git'), peer = path.join(directory, 'peer');
  const git = async (cwd: string, ...args: string[]) => (await exec('git', ['-C', cwd, ...args])).stdout.trim();
  const source = { readLocalProjects: async () => ({ projects: [] }) } as unknown as SourceBackend;
  const oldCredentials = process.env.DELIVERY_CREDENTIALS_FILE;
  process.env.DELIVERY_CREDENTIALS_FILE = path.join(directory, 'fixture.env');
  const act = async (action: string, extra: Record<string, unknown> = {}) => executeProjectGitAction({ path: repo, revision: (await readProjectGitSnapshot(repo)).revision, action, ...extra }, source);
  const write = (file: string, content: string) => fs.writeFile(path.join(repo, file), content);
  try {
    await fs.mkdir(repo); await git(repo, 'init', '-q', '-b', 'main');
    await git(repo, 'config', 'user.name', 'Git Fixture'); await git(repo, 'config', 'user.email', 'fixture@localhost');
    await write('value.txt', 'base\n'); await git(repo, 'add', '.'); await git(repo, 'commit', '-qm', '初始化验证仓库');
    await git(directory, 'init', '--bare', '-q', '--initial-branch=main', remote);
    await act('connect', { name: 'origin', url: remote });
    await write('value.txt', 'updated\n');
    assert.match((await readProjectDiff(repo, 'value.txt', false)).patch, /updated/);
    await act('stage', { files: ['value.txt'] }); assert.equal((await readProjectGitSnapshot(repo)).counts.staged, 1);
    assert.match((await readProjectDiff(repo, 'value.txt', true)).patch, /updated/);
    await act('unstage', { files: ['value.txt'] }); assert.equal((await readProjectGitSnapshot(repo)).counts.staged, 0);
    await act('stage-all'); await act('commit', { message: '更新验证内容' });
    await act('push', { remote: 'origin' });
    assert.equal(await git(remote, 'rev-parse', 'main'), await git(repo, 'rev-parse', 'HEAD'));
    assert.match((await act('test-remote', { remote: 'origin' })).output, /连接成功/);
    await act('create-branch', { branch: 'feature/git-smoke' });
    await write('feature.txt', 'feature\n'); await act('stage-all'); await act('commit', { message: '验证功能分支' });
    await act('switch', { ref: 'refs/heads/main' }); await act('merge', { ref: 'refs/heads/feature/git-smoke' });
    assert.equal(await fs.readFile(path.join(repo, 'feature.txt'), 'utf8'), 'feature\n');
    await act('push', { remote: 'origin' });
    await git(directory, 'clone', '-q', remote, peer); await git(peer, 'config', 'user.name', 'Peer Fixture'); await git(peer, 'config', 'user.email', 'peer@localhost');
    await fs.writeFile(path.join(peer, 'peer.txt'), 'peer\n'); await git(peer, 'add', '.'); await git(peer, 'commit', '-qm', '验证拉取'); await git(peer, 'push', '-q');
    await act('fetch', { remote: 'origin' }); assert.equal((await readProjectGitSnapshot(repo)).behind, 1);
    await act('pull'); assert.equal(await git(repo, 'rev-parse', 'HEAD'), await git(peer, 'rev-parse', 'HEAD'));
    const stale = (await readProjectGitSnapshot(repo)).revision;
    await write('value.txt', 'dirty\n');
    await assert.rejects(executeProjectGitAction({ path: repo, revision: stale, action: 'stage-all' }, source), /状态已变化/);
    await assert.rejects(act('switch', { ref: 'refs/heads/feature/git-smoke' }), /请先提交/);
    assert.equal(await fs.readFile(path.join(repo, 'value.txt'), 'utf8'), 'dirty\n');
    await act('stage-all'); await act('commit', { message: '验证主分支改动' });
    await act('switch', { ref: 'refs/heads/feature/git-smoke' });
    await write('value.txt', 'conflict\n'); await act('stage-all'); await act('commit', { message: '验证合并冲突' });
    await act('switch', { ref: 'refs/heads/main' });
    assert.equal((await act('merge', { ref: 'refs/heads/feature/git-smoke' })).outcome, 'merge-conflicts');
    assert.equal((await readProjectGitSnapshot(repo)).mergeInProgress, true);
    await act('abort-merge'); assert.equal((await readProjectGitSnapshot(repo)).clean, true);
    await write('.env.local', 'fixture-only');
    assert.ok(!(await readProjectTree(repo)).entries.some(item => item.name === '.env.local'));
    await assert.rejects(readProjectCode(repo, '.env.local'));
    assert.equal((await readProjectCode(repo, 'value.txt')).content, 'dirty\n');
    await assert.rejects(readProjectCode(repo, '../outside'));
    await fs.rm(path.join(repo, '.env.local'));
    const linked = path.join(directory, 'linked'); await git(repo, 'worktree', 'add', '-q', linked, 'feature/git-smoke');
    assert.equal((await readProjectGitSnapshot(linked)).branch, 'feature/git-smoke');
    const result = await executeProjectGitAction({ action: 'clone', parent: directory, folder: 'cloned', url: remote }, source);
    assert.equal(result.snapshot!.isGit, true);
  } finally {
    if (oldCredentials === undefined) delete process.env.DELIVERY_CREDENTIALS_FILE; else process.env.DELIVERY_CREDENTIALS_FILE = oldCredentials;
    await fs.rm(directory, { recursive: true, force: true });
  }
});
